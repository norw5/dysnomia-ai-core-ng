#!/usr/bin/env python3
"""Ship the never-deployed layer's pinned creation bytecode with the app.

Session 81 (SIM in-frontend bootstrap, Option A): the frontend deploys the
four layer creations on a LOCAL anvil fork as the impersonated LIVE deployer.
That needs the exact byte-pinned creation bytes at runtime — this tool copies
them from `harness/fixtures/world-layer/pins/` into `app/src/data/sim_layer/`
and writes a manifest with sha256 per file + provenance.

The pins are themselves generated by `harness/fixtures/world-layer/build.py`
(solc 0.8.21, shanghai, optimizer 200 — the pinned toolchain); this script
never compiles and never hand-edits bytes. Re-run it only when the fixture
sources/pins change:

    python3 tools/dys_sim_bundle.py

Output (app/src/data/sim_layer/):
  encrypt.creation.hex      ENCRYPT   (verbatim, self-registers on VOID)
  worldfixed.creation.hex   WORLDFIXED (fixture-fixed WORLD + VITUSFIXED)
  warfixed.creation.hex     WARFIXED  (fixture-fixed WAR + H2OFIXED)
  gwat.creation.hex         GWAT      (verbatim)
  manifest.json             file hashes + compiler/pin/source provenance

The static fixture overlay `config/sim_addresses.json` stays the harness path
(generated by set 3). The runtime overlay written by the app is the user path.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PINS = ROOT / "harness" / "fixtures" / "world-layer" / "pins"
SOURCES = ROOT / "harness" / "fixtures" / "world-layer" / "sources.manifest"
OUT = ROOT / "app" / "src" / "data" / "sim_layer"

# bundle key -> (contract artifact, pin basename)
FILES: dict[str, tuple[str, str]] = {
    "encrypt": ("ENCRYPT", "encrypt"),
    "worldfixed": ("WORLDFIXED", "worldfixed"),
    "warfixed": ("WARFIXED", "warfixed"),
    "gwat": ("GWAT", "gwat"),
}

PIN = 27_674_000

VARIANTS = {
    "ENCRYPT": "verbatim (self-registers as VOID's 'encrypt' library in its constructor)",
    "WORLDFIXED": "fixture-fixed WORLD (+ VITUSFIXED inside): the verbatim constructor callback loop is patched; the cauda write is wired",
    "WARFIXED": "fixture-fixed WAR (+ H2OFIXED inside): the verbatim constructor callback loop is patched",
    "GWAT": "verbatim (read-only constructor against the live perimeter + WAR)",
}


def sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> int:
    if not SOURCES.exists():
        raise SystemExit(f"source manifest missing: {SOURCES}")
    OUT.mkdir(parents=True, exist_ok=True)
    files: dict[str, dict[str, object]] = {}
    for key, (contract, pin_name) in FILES.items():
        src = PINS / f"{pin_name}.creation.hex"
        if not src.exists():
            raise SystemExit(f"pin missing: {src} (run harness/fixtures/world-layer/build.py)")
        raw = src.read_text().strip().removeprefix("0x")
        if len(raw) < 100 or len(raw) % 2 != 0:
            raise SystemExit(f"pin looks invalid: {src}")
        dst = OUT / f"{key}.creation.hex"
        dst.write_text(raw + "\n")
        files[key] = {
            "file": dst.name,
            "contract": contract,
            "bytes": len(raw) // 2,
            "sha256": sha256_file(dst),
        }
    manifest = {
        "v": 1,
        "generatedBy": "tools/dys_sim_bundle.py",
        "pin": PIN,
        "compiler": "solc 0.8.21 (svm) · --evm-version shanghai --optimize --optimize-runs 200",
        "sourceRevision": "harness/fixtures/world-layer/sources.manifest",
        "sourceManifestSha256": sha256_file(SOURCES),
        "fixedVariants": "WORLDFIXED/WARFIXED are the fixture-fixed pair (VITUSFIXED/H2OFIXED deploy inside their constructors); ENCRYPT/GWAT are verbatim. The app ABIs are the WORLD/WAR interfaces; the deployed names in the runtime overlay stay WORLD/WAR.",
        "variants": VARIANTS,
        "files": files,
    }
    (OUT / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    total = sum(int(v["bytes"]) for v in files.values())
    print(f"wrote {OUT} · {len(files)} creation files · {total} bytes binary")
    for key, meta in files.items():
        print(f"  {key:12s} {meta['bytes']:>7} B  {meta['sha256']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
